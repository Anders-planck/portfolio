import { Theme } from '@astryxdesign/core/theme'
import { convexQuery } from '@convex-dev/react-query'
import { type QueryClient, useSuspenseQuery } from '@tanstack/react-query'
import {
  createRootRouteWithContext,
  HeadContent,
  Outlet,
  Scripts,
} from '@tanstack/react-router'
import type { ReactNode } from 'react'
import { api } from '../../convex/_generated/api'
import type { ColorMode } from '../../convex/lib/appearance'
import { defaultThemeSlug, themes } from '../astryx-themes'
import globalsCss from '../styles/globals.css?url'

const baseTheme = themes[defaultThemeSlug]
const appearanceQuery = convexQuery(api.siteSettings.getAppearance, {})

export const Route = createRootRouteWithContext<{
  queryClient: QueryClient
}>()({
  // The published theme and motion params are read on the server, so the
  // first paint already has them (ADR 0010).
  loader: ({ context }) => context.queryClient.ensureQueryData(appearanceQuery),
  head: () => ({
    meta: [
      { charSet: 'utf-8' },
      { name: 'viewport', content: 'width=device-width, initial-scale=1' },
      { title: 'Anders Planck' },
    ],
    // globals.css must be the first stylesheet: it declares the cascade-layer
    // order. The theme CSS imported by astryx-themes is linked after it.
    links: [{ rel: 'stylesheet', href: globalsCss }],
  }),
  component: RootComponent,
})

function RootComponent() {
  // Live: a publish restyles open pages without a reload.
  const { data } = useSuspenseQuery(appearanceQuery)
  return (
    <RootDocument mode={data.appearance.theme.mode} appearanceCss={data.css}>
      <Outlet />
    </RootDocument>
  )
}

function RootDocument({
  mode,
  appearanceCss,
  children,
}: {
  mode: ColorMode
  appearanceCss: string
  children: ReactNode
}) {
  return (
    // Set on the server, so the first paint has the mode; <Theme> keeps them
    // in sync after hydration.
    <html
      lang="it"
      data-astryx-theme={baseTheme.name}
      data-theme={mode === 'system' ? undefined : mode}
    >
      <head>
        <HeadContent />
        {/* After the built theme stylesheet, so the params win by order. */}
        <style
          data-appearance=""
          // biome-ignore lint/security/noDangerouslySetInnerHtml: generated by Astryx in Convex from validated params; font names are allow-listed (ADR 0010).
          dangerouslySetInnerHTML={{ __html: appearanceCss }}
        />
      </head>
      <body>
        <Theme theme={baseTheme} mode={mode}>
          {children}
        </Theme>
        <Scripts />
      </body>
    </html>
  )
}
